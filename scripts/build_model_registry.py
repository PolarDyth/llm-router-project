#!/usr/bin/env python3
"""Build the model complexity registry.

Thin CLI over `router.catalogs` (acquire + merge the four vendor catalogs) and
`router.scoring` (assign tiers). All the rules and their rationale live in those
modules; this file parses arguments, orders the stages, and renders the report.

  1 = tiny/flash class          4 = pro/legacy-frontier class
  2 = mini/light class          5 = frontier class
  3 = mid/pro class

Usage:
  python scripts/build_model_registry.py [--refresh]

Outputs:
  data/model_registry/models.json       the registry (checked in)
  data/model_registry/build_report.md   disagreements + coverage stats (local)
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

from router.catalogs import CatalogCache, merge_records
from router.contracts import COMPLEXITY_SCALE
from router.scoring import alias_collisions, apply_overrides, load_overrides, score_all

ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / "data" / "model_registry" / "cache"
OUT_JSON = ROOT / "data" / "model_registry" / "models.json"
OUT_OVERRIDES = ROOT / "data" / "model_registry" / "overrides.yaml"
OUT_REPORT = ROOT / "data" / "model_registry" / "build_report.md"


def log(msg: str) -> None:
    print(msg, file=sys.stderr)


def build(cache: CatalogCache, overrides: dict[str, Any]) -> tuple[list[dict[str, Any]], list[str]]:
    """Run the pipeline: catalogs -> groups -> scored entries -> hand overrides."""
    recs = cache.records()
    log(f"records: litellm+openrouter+models.dev = {len(recs)}")
    epoch = cache.epoch()
    log(f"epoch language models with dates: {len(epoch)}")

    groups = merge_records(recs, epoch)
    log(f"canonical groups: {len(groups)}")

    # excluded keys are junk merge groups; the real model is recreated below
    built = score_all(groups, set(overrides.get("excludes") or []))
    built = apply_overrides(built, overrides)
    return built, alias_collisions(built)


def render_report(
    built: list[dict[str, Any]],
    collisions: list[str],
    tier_hist: dict[int, int],
    generated_at: str,
    out_report: Path = OUT_REPORT,
) -> None:
    flagged = sorted(
        (e for e in built if e["notes"] or e["basis"] == "guess"),
        key=lambda e: e["canonical_id"],
    )
    out_report.parent.mkdir(parents=True, exist_ok=True)
    with out_report.open("w") as f:
        f.write("# registry build report\n\n")
        f.write(f"generated: {generated_at}\n\n")
        f.write(
            f"models: {len(built)} | tier histogram: {dict(sorted(tier_hist.items()))}\n\n"
        )
        f.write(f"alias collisions: {len(collisions)}\n")
        for c in collisions[:50]:
            f.write(f"- {c}\n")
        f.write(
            "\n## flagged for review (quality-adjusted, guessed, or era-capped)\n\n"
        )
        for e in flagged:
            f.write(
                f"- **{e['complexity']}** {e['canonical_id']} | {e['basis']} | {e['notes']}\n"
            )
        f.write("\n## sample by tier (spot check)\n\n")
        seen: dict[int, list[str]] = defaultdict(list)
        for e in sorted(built, key=lambda x: -(x["signals"]["intelligence_index"] or 0)):
            if len(seen[e["complexity"]]) < 12:
                seen[e["complexity"]].append(e["canonical_id"])
        for tier in sorted(seen):
            f.write(f"### tier {tier}\n")
            for mid in seen[tier]:
                f.write(f"- {mid}\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--refresh", action="store_true", help="re-download catalogs")
    ap.add_argument("--cache", type=Path, default=CACHE,
                    help="directory holding the downloaded vendor catalogs")
    ap.add_argument("--out", type=Path, default=OUT_JSON,
                    help="registry JSON to write (the committed one by default)")
    ap.add_argument("--report", type=Path, default=OUT_REPORT,
                    help="build report to write")
    args = ap.parse_args()

    cache = CatalogCache(args.cache)
    cache.refresh(force=args.refresh)

    overrides = load_overrides(OUT_OVERRIDES)
    built, collisions = build(cache, overrides)

    tier_hist: dict[int, int] = defaultdict(int)
    for e in built:
        tier_hist[e["complexity"]] += 1

    generated_at = dt.datetime.now(dt.UTC).isoformat(timespec="seconds")
    registry = {
        "schema_version": 1,
        "generated_at": generated_at,
        "description": "Model complexity registry: canonical chat LLMs (2022-2026) -> complexity 1-5. Generated by scripts/build_model_registry.py; hand fixes live in overrides.yaml.",
        "complexity_scale": COMPLEXITY_SCALE,
        "models": sorted(built, key=lambda e: e["canonical_id"]),
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(registry, indent=1, ensure_ascii=False) + "\n")
    log(f"wrote {args.out} ({len(built)} models)")

    render_report(built, collisions, dict(tier_hist), generated_at, args.report)
    log(f"wrote {args.report}")
    log(f"tier histogram: {dict(sorted(tier_hist.items()))}")
    if collisions:
        log(f"WARNING: {len(collisions)} alias collisions - see report")


if __name__ == "__main__":
    main()
